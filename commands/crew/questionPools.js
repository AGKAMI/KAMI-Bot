/**
 * Question Pools — 4 teams × 6 categories × 30 variants = 720 questions
 * Each team has completely unique application experience.
 * Questions are randomly selected per application, answers shuffled.
 */

function shuffle(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

